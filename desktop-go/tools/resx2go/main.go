// resx2go turns entries of a .resx file (the C# app's Messages.resx, FriendlyNames.resx) into a Go map, so the Go app
// shows the same texts. Usage (see internal/messages/messages.go):
//
//	go run ./tools/resx2go -var name -prefix A_,B_ -o out.go file.resx
package main

import (
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

type resx struct {
	Data []struct {
		Name  string `xml:"name,attr"`
		Value string `xml:"value"`
	} `xml:"data"`
}

func main() {
	out := flag.String("o", "", "output .go file")
	name := flag.String("var", "texts", "map variable name")
	prefixes := flag.String("prefix", "", "comma-separated key prefixes to keep, or @file with one per line")
	flag.Parse()
	if *out == "" || flag.NArg() != 1 || *prefixes == "" {
		log.Fatal("usage: resx2go -o out.go -var name -prefix P1,P2 file.resx")
	}
	// a long list goes in a file: go generate refuses directives over 4 KB
	if file, ok := strings.CutPrefix(*prefixes, "@"); ok {
		b, err := os.ReadFile(file)
		if err != nil {
			log.Fatal(err)
		}
		*prefixes = strings.Join(strings.Fields(string(b)), ",")
	}
	raw, err := os.ReadFile(flag.Arg(0))
	if err != nil {
		log.Fatal(err)
	}
	var r resx
	if err := xml.Unmarshal(raw, &r); err != nil {
		log.Fatal(err)
	}
	keep := map[string]string{}
	for _, d := range r.Data {
		for _, p := range strings.Split(*prefixes, ",") {
			if strings.HasPrefix(d.Name, p) {
				keep[d.Name] = d.Value
			}
		}
	}
	keys := make([]string, 0, len(keep))
	for k := range keep {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/resx2go from %s; DO NOT EDIT.\n\npackage messages\n\nvar %s = map[string]string{\n",
		flag.Arg(0)[strings.LastIndex(flag.Arg(0), "/")+1:], *name)
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(k), strconv.Quote(keep[k]))
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
